/**
 * Fetch Order Book
 * Returns current bids and asks for a trading pair
 * Uses data-service for proper Money/BigNumber conversion
 *
 * @param amountAsset - Amount asset ID
 * @param priceAsset - Price asset ID
 * @param depth - Number of price levels to return (default 50)
 * @param options - React Query options
 */
export const useOrderBook = (
  amountAsset: string,
  priceAsset: string,
  depth = 50,
  options?: {
    enabled?: boolean;
    refetchInterval?: number;
  },
): UseQueryResult<OrderBook, Error> => {
  return useQuery({
    enabled: !!amountAsset && !!priceAsset && options?.enabled !== false,
    queryFn: async () => {
      // Use data-service which properly converts Money objects
      interface DsOrderEntry {
        amount: { getTokens(): { toNumber(): number } };
        price: { getTokens(): { toNumber(): number } };
      }
      interface DsOrderBook {
        bids: DsOrderEntry[];
        asks: DsOrderEntry[];
        pair: { amountAsset: { id: string }; priceAsset: { id: string } };
      }
      const orderBookData = (await ds.api.matcher.getOrderBook(
        amountAsset,
        priceAsset,
      )) as DsOrderBook;

      // Convert Money objects to numbers (in token units, not smallest units)
      const bids = orderBookData.bids.slice(0, depth).map((bid) => ({
        amount: bid.amount.getTokens().toNumber(),
        price: bid.price.getTokens().toNumber(),
      }));

      const asks = orderBookData.asks.slice(0, depth).map((ask) => ({
        amount: ask.amount.getTokens().toNumber(),
        price: ask.price.getTokens().toNumber(),
      }));

      return {
        asks,
        bids,
        pair: {
          amountAsset: orderBookData.pair.amountAsset.id,
          priceAsset: orderBookData.pair.priceAsset.id,
        },
        timestamp: Date.now(),
      };
    },
    queryKey: ['orderbook', amountAsset, priceAsset, depth],
    // The matcher exposes no WebSocket feed (/ws/v0 is 404 on 2.3.2.9), so the
    // book is polled. 2s rather than 5s: the Angular app this replaced polled at
    // 1s, and a five-second-old book on a trading screen reads as broken. React
    // Query pauses intervals for hidden tabs, so this costs nothing while the
    // user is on another tab — but it is ~2.5x the matcher request volume of the
    // previous setting for tabs that are open and looking at the DEX.
    refetchInterval: options?.refetchInterval ?? 2000,
    // Refetch when the user returns to the tab. Polling is suspended while
    // hidden, so without this the first thing they see is whatever the book
    // looked like when they left.
    refetchOnWindowFocus: true,
    retry: 2, // Retry failed requests up to 2 times
    retryDelay: (attemptIndex) => Math.min(1000 * 2 ** attemptIndex, 30000), // Exponential backoff
    staleTime: 1000,
  });
};

/**
 * Fetch User Orders
 * Returns order history for a specific asset pair and public key.
 * Requires matcher authentication via Timestamp + Signature headers.
 * The signature is generated at login and stored in user.matcherSign (1-day validity).
 * @see GET /matcher/orderbook/{amountAsset}/{priceAsset}/publicKey/{publicKey}
 *
 * @param publicKey - User's base58-encoded public key
 * @param matcherSign - Pre-generated matcher auth { timestamp (ms, future), signature (base58) }
 * @param amountAsset - Optional: filter by amount asset
 * @param priceAsset - Optional: filter by price asset
 * @param options - React Query options
 */
export const useUserOrders = (
  publicKey: string,
  matcherSign: { timestamp: number; signature: string } | undefined,
  amountAsset?: string,
  priceAsset?: string,
  options?: {
    enabled?: boolean;
    refetchInterval?: number;
  },
): UseQueryResult<Order[], Error> => {
  return useQuery({
    enabled:
      !!publicKey &&
      !!matcherSign?.signature &&
      !!amountAsset &&
      !!priceAsset &&
      options?.enabled !== false,
    queryFn: async () => {
      if (!matcherSign) throw new Error('Matcher sign required');
      const { data } = await matcherClient.get<Order[]>(
        `/orderbook/${amountAsset}/${priceAsset}/publicKey/${publicKey}`,
        {
          headers: {
            Signature: matcherSign.signature,
            Timestamp: String(matcherSign.timestamp),
          },
        },
      );
      return data;
    },
    queryKey: ['orders', publicKey, amountAsset, priceAsset, matcherSign?.timestamp],
    refetchInterval: options?.refetchInterval ?? 10000,
    refetchOnWindowFocus: false,
    retry: 0, // matcher auth fails fast — never retry, prevents 400 loop
    staleTime: 5000,
  });
};

/**
 * Fetch Order History
 * Returns all historical orders for a user address.
 * Requires matcher authentication via Timestamp + Signature headers.
 * The signature is generated at login and stored in user.matcherSign (1-day validity).
 * @see GET /matcher/orderbook/{address} and GET /matcher/orderbook/{address}/activeOnly
 *
 * @param address - User address
 * @param matcherSign - Pre-generated matcher auth { timestamp (ms, future), signature (base58) }
 * @param activeOnly - Filter to active orders only
 * @param options - React Query options
 */
export const useOrderHistory = (
  address: string,
  matcherSign: { timestamp: number; signature: string } | undefined,
  activeOnly = false,
  options?: {
    enabled?: boolean;
    refetchInterval?: number;
  },
): UseQueryResult<Order[], Error> => {
  return useQuery({
    enabled: !!address && !!matcherSign?.signature && options?.enabled !== false,
    queryFn: async () => {
      if (!matcherSign) throw new Error('Matcher sign required');
      const status = activeOnly ? '/activeOnly' : '';
      const { data } = await matcherClient.get<Order[]>(`/orderbook/${address}${status}`, {
        headers: {
          Signature: matcherSign.signature,
          Timestamp: String(matcherSign.timestamp),
        },
      });
      return data;
    },
    queryKey: ['orders', 'history', address, activeOnly, matcherSign?.timestamp],
    refetchInterval: options?.refetchInterval ?? 30_000,
    refetchOnWindowFocus: false,
    retry: 2,
    retryDelay: (attemptIndex) => Math.min(1000 * 2 ** attemptIndex, 30000),
    staleTime: 30_000,
  });
};

/**
 * Fetch Trade History
 * Returns recent trades for a trading pair
 * Note: Trades come from exchange transactions on the blockchain,
 * not from the matcher API. This requires using the data-service.
 *
 * @param amountAsset - Amount asset ID
 * @param priceAsset - Price asset ID
 * @param limit - Number of trades to return
 * @param options - React Query options
 */
export const useTradeHistory = (
  amountAsset: string,
  priceAsset: string,
  limit = 100,
  options?: {
    enabled?: boolean;
    refetchInterval?: number;
  },
): UseQueryResult<Trade[], Error> => {
  return useQuery({
    enabled: !!amountAsset && !!priceAsset && options?.enabled !== false,
    queryFn: async () => {
      const result = await getExchangeTxList({ amountAsset, limit, priceAsset });
      const txs = (result ?? []) as unknown as RawExchangeTx[];
      return txs.map((tx) => ({
        amount: tx.amount,
        id: tx.id,
        pair: `${amountAsset}/${priceAsset}`,
        price: tx.price,
        timestamp: tx.timestamp,
        type: (tx.order1?.orderType === 'sell' ? 'sell' : 'buy') as OrderSide,
      }));
    },
    queryKey: ['trades', amountAsset, priceAsset, limit],
    refetchInterval: options?.refetchInterval ?? 10000,
    refetchOnWindowFocus: false,
    retry: 2,
    retryDelay: (attemptIndex) => Math.min(1000 * 2 ** attemptIndex, 30000),
    staleTime: 5000,
  });
};

