/**
 * Matcher API Service
 * Handles DEX matcher endpoints for trading operations
 */
import {
  type UseMutationResult,
  type UseQueryResult,
  useMutation,
  useQuery,
} from '@tanstack/react-query';
import * as ds from 'data-service';
import { getExchangeTxList } from '@/lib/data-service/api/transactions/transactions';
import { apiClient, matcherClient } from '../client';

/**
 * Raw exchange transaction shape returned by the data-service exchange tx list endpoint.
 * Declared at module scope so the queryFn can reference it without a local type alias.
 */
interface RawExchangeTx {
  id: string;
  timestamp: number;
  price: number;
  amount: number;
  order1?: { orderType: string };
}

/**
 * Order Side Enum
 */
export type OrderSide = 'buy' | 'sell';

/**
 * Order Status Enum
 */
export type OrderStatus = 'Accepted' | 'PartiallyFilled' | 'Filled' | 'Cancelled';

/**
 * Order Book Entry
 */
export interface OrderBookEntry {
  price: number;
  amount: number;
}

/**
 * Order Book Response
 */
export interface OrderBook {
  timestamp: number;
  pair: {
    amountAsset: string;
    priceAsset: string;
  };
  bids: OrderBookEntry[];
  asks: OrderBookEntry[];
}

/**
 * Order Interface
 * Matches the order shape in both history responses and the place-order response `message` field.
 * `assetPair.amountAsset / priceAsset` are `string | null`: null means native DCC (per Dcc matcher docs
 * "DCC, or null, or omitted field means DCC/DCC").
 */
export interface Order {
  id: string;
  /** Direction: "buy" or "sell" */
  type: OrderSide;
  /** Execution style: "limit" or "market" (returned by history endpoints) */
  orderType: 'limit' | 'market';
  amount: number;
  price: number;
  timestamp: number;
  expiration: number;
  matcherFee: number;
  status: OrderStatus;
  assetPair: {
    amountAsset: string | null;
    priceAsset: string | null;
  };
  filled: number;
  filledFee?: number;
  avgFilledPrice?: number;
}

/**
 * Trade/Match Interface
 */
export interface Trade {
  id: string;
  timestamp: number;
  price: number;
  amount: number;
  type: OrderSide; // buyer or seller perspective
  pair: string;
}

/**
 * Order Creation Data
 * Matches the signed order body accepted by the DCC matcher API.
 * Use `order()` from @decentralchain/transactions to produce a properly signed value.
 */
export interface CreateOrderData {
  /** Computed by the order() builder; included in the signed order body. */
  id?: string;
  /** Order side: 'buy' or 'sell' — NOT the limit/market distinction. */
  orderType: 'buy' | 'sell';
  /** LONG: string for amounts that may exceed Number.MAX_SAFE_INTEGER, number for typical amounts. */
  amount: number | string;
  /** LONG: string for prices that may exceed Number.MAX_SAFE_INTEGER, number for typical prices. */
  price: number | string;
  matcherFee: number;
  matcherFeeAssetId?: string | null;
  matcherPublicKey: string;
  assetPair: {
    amountAsset: string | null;
    priceAsset: string | null;
  };
  timestamp: number;
  expiration: number;
  senderPublicKey: string;
  /** Base58-encoded proofs generated by order() signing. */
  proofs: string[];
  version?: number;
}

/**
 * Matcher Settings
 * `orderFee` supports multiple fee modes depending on the matcher configuration.
 * The DCC and Dcc matchers support: dynamic, percent, fixed, and composite (which
 * nests the above under `composite.default`). Always use `getMatcherBaseFee()` to extract
 * the base fee — never access `orderFee.dynamic` directly.
 */
export interface MatcherSettings {
  matcherPublicKey: string;
  matcherVersion: string;
  priceAssets: string[];
  orderFee: MatcherOrderFee;
}

/**
 * All fee modes supported by the Dcc/DCC matcher.
 * At most one of the top-level keys will be present in a given response.
 */
export interface MatcherOrderFee {
  /** Simple dynamic mode: fee scales with order size. */
  dynamic?: { baseFee: number };
  /** Fixed fee in a specific asset. */
  fixed?: { assetId: string | null; minFee: number };
  /** Percent fee based on order amount. */
  percent?: {
    type: 'amount' | 'price' | 'spending' | 'receiving';
    minFee: number;
    minFeeInDcc: number;
  };
  /**
   * Composite mode (used in production): wraps dynamic/percent/fixed under a `default` key,
   * with optional per-pair overrides in `custom` and a discount asset in `discount`.
   */
  composite?: {
    default: MatcherOrderFee;
    custom?: Record<string, MatcherOrderFee>;
    discount?: { assetId: string; value: number };
  };
}

/**
 * Extract the base fee (in dcclets) from any matcher fee configuration.
 * Walks composite nesting and falls back to 300 000 dcclets (0.003 DCC — the
 * protocol default) when the mode is unrecognised or the field is missing.
 *
 * @param fee - The `orderFee` object from `GET /matcher/settings`.
 */
export function getMatcherBaseFee(fee: MatcherOrderFee): number {
  if (fee.dynamic?.baseFee != null) {
    return fee.dynamic.baseFee;
  }
  if (fee.composite?.default != null) {
    return getMatcherBaseFee(fee.composite.default);
  }
  if (fee.fixed?.minFee != null) {
    return fee.fixed.minFee;
  }
  if (fee.percent?.minFeeInDcc != null) {
    return fee.percent.minFeeInDcc;
  }
  // Default DCC/Dcc matcher fee: 0.003 DCC = 300 000 dcclets.
  return 300_000;
}

